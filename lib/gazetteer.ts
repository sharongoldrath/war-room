export function geotag(text: string): [number, number] | null {
  for (const p of PLACES) {
    for (const n of p.names) {
      // Latin names: word boundary; Hebrew: substring (prefixes like ב/ל/מ are common)
      const hit = /[a-z]/i.test(n) ? new RegExp(`\\b${n.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\b`, 'i').test(text) : text.includes(n);
      if (hit) return [p.lon, p.lat];
    }
  }
  return null;
}
